# -*- coding: utf-8 -*-
"""
第 01 章：开发环境搭建与第一个程序
对应教材：第一部分-Python入门基础/01-开发环境搭建与第一个程序.md

说明：
- 本章主要是环境安装介绍，这里演示「两种运行方式」中的脚本方式、
  print()、注释的写法，以及交互式解释器的例子改写为普通代码。
- md 练习题第 4 题里的「故意错误示范」（全角括号、Print 大小写、缺引号）
  按要求没有收录，本脚本只保留可运行的正确代码。
"""


def section(title):
    print("\n" + "=" * 40)
    print(title)
    print("=" * 40)


section("1. Hello, World!")

# 第一个程序：把内容打印到屏幕上
print("Hello, World!")
print("我的第一个 Python 程序")

section("2. print() 的基本拆解")

# print 是函数：括号里是字符串参数，字符串必须用引号包裹
print("Hello, World!")        # 双引号
print('也可以用单引号')        # 单引号效果相同
print(3 + 5)                  # 还可以直接打印计算结果：8

section("3. 注释：写给人看的说明")

# 这是一行注释，程序不会执行它
print("Hello")  # 井号后面的内容也是注释

# 下面这行被注释掉了，不会运行
# print("我不会被打印")

# 多行说明用三引号包裹（文档字符串，常当多行注释用）
"""
这是一段
多行说明文字。
"""
print("正文代码")

section("4. 个人名片小练习（md 练习题第 2 题）")

# 三条 print 分别打印昵称、座右铭、学习目标
print("昵称：小明")
print("座右铭：慢慢来，比较快")
print("目标：三个月内完成一个机器学习项目")

section("5. 交互式解释器里的例子（已改写为普通代码）")

# md 里交互式示例：>>> 1 + 1 → 2，这里直接打印
print(1 + 1)              # 2
print("你好")             # 你好
print(10 * 8)             # 80

# md 练习题第 3 题：交互式计算 2024 * 365
print(2024 * 365)         # 738760

# md 练习题第 5 题：给代码补充注释
print("欢迎")             # 在屏幕上打印“欢迎”两个字
print(3 + 5)              # 先计算 3+5=8，再把结果 8 打印出来

print("\n第 01 章演示完毕 ✅")
